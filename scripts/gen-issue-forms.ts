// author: Stephen Eaton
// Generate GitHub issue forms from the taxonomy so dropdowns never drift.
// Usage: bun scripts/gen-issue-forms.ts   (re-run after any taxonomy change; tests fail if stale)
import { mkdirSync, writeFileSync } from 'node:fs';
import { stringify } from 'yaml';
import { loadTaxonomy } from './lib/taxonomy';

const t = loadTaxonomy('taxonomy');
const SITE = 'https://agentpractices.dev';
const active = t.concepts.filter((c) => c.status !== 'deprecated');
const tops = active.filter((c) => !c.broader);
const header = '# author: Stephen Eaton\n# GENERATED by scripts/gen-issue-forms.ts from taxonomy/*.yaml — do not edit by hand.\n';
const out = (f: string, o: object) => writeFileSync(`.github/ISSUE_TEMPLATE/${f}`, header + stringify(o, { lineWidth: 0 }));
mkdirSync('.github/ISSUE_TEMPLATE', { recursive: true });

out('propose-practice.yml', {
  name: 'Propose a practice',
  description: 'Propose a new best practice. The owner assigns the BP-NNNN ID when the proposal is accepted.',
  title: '[Practice]: ',
  labels: ['proposal', 'practice'],
  body: [
    { type: 'markdown', attributes: { value: `Read [Add a practice](${SITE}/contributing/add-a-practice/) first. Do not pick an ID; the owner assigns one on acceptance. Agents filing this form: fill every required field and cite sources.` } },
    { type: 'input', id: 'practice_title', attributes: { label: 'Practice title', description: 'Imperative, e.g. "Pin MCP server versions".' }, validations: { required: true } },
    { type: 'textarea', id: 'problem', attributes: { label: 'Problem', description: 'What goes wrong today without this practice? Include an example if you have one.' }, validations: { required: true } },
    { type: 'dropdown', id: 'domain', attributes: { label: 'Domain', description: `Most specific concept that fits (see ${SITE}/taxonomy.json).`, options: [...active.map((c) => `${c.id} — ${c.label}`), 'None fits — needs a taxonomy change'] }, validations: { required: true } },
    { type: 'dropdown', id: 'type', attributes: { label: 'Type', options: t.facets.type.map((f) => f.id) }, validations: { required: true } },
    { type: 'dropdown', id: 'roles', attributes: { label: 'Roles', multiple: true, options: t.facets.role.map((f) => f.id) }, validations: { required: true } },
    { type: 'dropdown', id: 'stage', attributes: { label: 'Stage', multiple: true, options: t.facets.stage.map((f) => f.id) }, validations: { required: true } },
    { type: 'textarea', id: 'rules', attributes: { label: 'Draft rules', description: 'Numbered, using MUST / SHOULD / MAY.', placeholder: '1. **MUST** …\n2. **SHOULD** …' }, validations: { required: true } },
    { type: 'textarea', id: 'related', attributes: { label: 'Related or overlapping practices', description: 'BP-IDs this relates to, extends or might duplicate.' } },
    { type: 'textarea', id: 'sources', attributes: { label: 'Sources', description: 'Links to standards, docs or evidence.' } },
    { type: 'checkboxes', id: 'checks', attributes: { label: 'Checks', options: [
      { label: 'I searched existing practices and open issues for duplicates', required: true },
      { label: 'The proposal contains no secrets or personal data', required: true },
    ] } },
  ],
});

out('propose-taxonomy-change.yml', {
  name: 'Propose a taxonomy change',
  description: 'Add, rename or retire a domain concept.',
  title: '[Taxonomy]: ',
  labels: ['proposal', 'taxonomy'],
  body: [
    { type: 'markdown', attributes: { value: `Read [Extend the taxonomy](${SITE}/contributing/extend-the-taxonomy/) first. IDs are permanent: renames change the label only; retirement deprecates with a replacement.` } },
    { type: 'dropdown', id: 'change', attributes: { label: 'Change', options: ['Add a concept', 'Rename a concept (label only)', 'Retire a concept (deprecate)'] }, validations: { required: true } },
    { type: 'dropdown', id: 'parent', attributes: { label: 'Parent domain', options: ['None (new top-level domain)', ...tops.map((c) => `${c.id} — ${c.label}`)] }, validations: { required: true } },
    { type: 'input', id: 'label', attributes: { label: 'Proposed label' }, validations: { required: true } },
    { type: 'textarea', id: 'definition', attributes: { label: 'Definition', description: 'Genus + differentia: "A <parent> practice governing …".' }, validations: { required: true } },
    { type: 'textarea', id: 'question', attributes: { label: 'Question it answers', description: 'Which practices would live here, and why no existing concept covers them (quote the closest definitions).' }, validations: { required: true } },
    { type: 'input', id: 'replaced_by', attributes: { label: 'Replaced by (retirements only)', description: 'Concept ID that replaces it.' } },
  ],
});

out('report-practice-problem.yml', {
  name: 'Report a problem with a practice',
  description: 'A rule is wrong, unclear, out of date or caused a bad outcome.',
  title: '[Problem]: BP-',
  labels: ['practice', 'problem'],
  body: [
    { type: 'input', id: 'practice', attributes: { label: 'Practice and version', placeholder: 'BP-0001@1.0.0' }, validations: { required: true } },
    { type: 'input', id: 'rule', attributes: { label: 'Rule number(s)', placeholder: 'R3' } },
    { type: 'dropdown', id: 'kind', attributes: { label: 'Kind of problem', options: ['Wrong or harmful', 'Unclear or ambiguous', 'Out of date', 'Conflicts with another practice', 'Broken link or typo'] }, validations: { required: true } },
    { type: 'textarea', id: 'what', attributes: { label: 'What happened', description: 'What you did following the rule, and what went wrong. Include evidence (commands, output, links).' }, validations: { required: true } },
    { type: 'textarea', id: 'fix', attributes: { label: 'Suggested change' } },
  ],
});

writeFileSync('.github/ISSUE_TEMPLATE/config.yml', header.replace('GENERATED by scripts/gen-issue-forms.ts from taxonomy/*.yaml — do not edit by hand.', 'Issue template chooser config.') + stringify({
  blank_issues_enabled: true,
  contact_links: [
    { name: 'How to contribute', url: `${SITE}/contributing/add-a-practice/`, about: 'Read before proposing a practice.' },
    { name: 'How agents use this site', url: `${SITE}/how-agents-use-this-site/`, about: 'Endpoints and citation format for agents.' },
  ],
}));
console.log(`issue forms: ${active.length} domain options, ${tops.length} parents`);
